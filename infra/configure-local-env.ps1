param(
  [string]$ResourceGroup = "soil-agri-rg",
  [string]$Suffix = "617db570",
  [string]$AlertEmailTo = "contact@beyondmarks.ai",
  [string]$AlertPhoneTo = "",
  [string]$SmsFrom = ""
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path $PSScriptRoot -Parent
$dashboard = Join-Path $repoRoot "smart-agri-dashboard"
$vault = "soilagrikv$Suffix"
$aiName = "soil-agri-ai-$Suffix"
$functionName = "soil-agri-functions-$Suffix"
$communicationName = "soil-agri-comms-$Suffix"
$emailName = "soil-agri-email-$Suffix"

$cosmos = az keyvault secret show --vault-name $vault --name cosmos-connection --query value -o tsv
$maps = az keyvault secret show --vault-name $vault --name azure-maps-key --query value -o tsv
$functionKey = az keyvault secret show --vault-name $vault --name function-key --query value -o tsv
$communication = az communication list-key -g $ResourceGroup -n $communicationName --query primaryConnectionString -o tsv
$aiEndpoint = az cognitiveservices account show -g $ResourceGroup -n $aiName --query properties.endpoint -o tsv
$aiKey = az cognitiveservices account keys list -g $ResourceGroup -n $aiName --query key1 -o tsv
$emailDomain = az communication email domain show -g $ResourceGroup --email-service-name $emailName -n AzureManagedDomain --query fromSenderDomain -o tsv

function EnvLine([string]$Name, [string]$Value) {
  if ($null -eq $Value) { $Value = "" }
  $escaped = $Value.Replace("\", "\\").Replace('"', '\"')
  return "$Name=`"$escaped`""
}

$lines = @(
  "# Generated by infra/configure-local-env.ps1. Never commit this file."
  (EnvLine "DISABLE_AUTH" "true")
  (EnvLine "LOCAL_SERIAL_CONTROL" "true")
  (EnvLine "SERIAL_BAUD" "9600")
  (EnvLine "COSMOS_CONNECTION_STRING" $cosmos)
  (EnvLine "COSMOS_DATABASE" "soil-agri")
  (EnvLine "AZURE_FUNCTION_BASE_URL" "https://$functionName.azurewebsites.net")
  (EnvLine "AZURE_FUNCTION_KEY" $functionKey)
  (EnvLine "AZURE_MAPS_KEY" $maps)
  (EnvLine "SOIL_AZURE_OPENAI_ENDPOINT" $aiEndpoint)
  (EnvLine "SOIL_AZURE_OPENAI_API_KEY" $aiKey)
  (EnvLine "SOIL_AZURE_OPENAI_DEPLOYMENT" "gpt-4.1-nano")
  (EnvLine "AZURE_COMMUNICATION_CONNECTION_STRING" $communication)
  (EnvLine "ACS_EMAIL_SENDER" "DoNotReply@$emailDomain")
  (EnvLine "ALERT_EMAIL_TO" $AlertEmailTo)
  (EnvLine "ACS_SMS_FROM" $SmsFrom)
  (EnvLine "ALERT_PHONE_TO" $AlertPhoneTo)
  (EnvLine "BLOCKCHAIN_RPC_URL" "https://polygon-amoy-bor-rpc.publicnode.com")
  (EnvLine "BLOCKCHAIN_PRIVATE_KEY" "")
  (EnvLine "BLOCKCHAIN_CONTRACT_ADDRESS" "")
)
$lines | Set-Content -Encoding utf8 (Join-Path $dashboard ".env.local")
Write-Output "Created smart-agri-dashboard/.env.local with Azure service settings."
if (-not $SmsFrom -or -not $AlertPhoneTo) { Write-Output "SMS remains disabled until ACS_SMS_FROM and ALERT_PHONE_TO are provided." }
